// One-time source extraction. The generated component is checked in and has no RN dependency.
import fs from 'node:fs/promises';
import vm from 'node:vm';

const source = await fs.readFile(new URL('../../YorollApp/yoroll-rn-main/node_modules/@yoroll/rn-icon/dist/index.js', import.meta.url), 'utf8');
const names = { play: 'IconPlayFilled', pause: 'IconPauseFilled', back: 'IconBackward', next: 'IconAngleright',
  chat: 'IconMessage', list: 'IconFoldedMenu', send: 'IconSendrequest', close: 'IconClose', restart: 'IconReplayFilled',
  expand: 'IconVideoFullscreenFilled', collapse: 'IconVideoClosefullscreenFilled' };
const jsx = (tag, props) => ({ tag, props });
function markup({ tag, props }) {
  const children = [props.children ?? []].flat().map(markup).join('');
  const attrs = Object.entries(props).filter(([key, value]) => key !== 'children' && key !== 'style' && value !== undefined)
    .map(([key, value]) => ` ${key}={${JSON.stringify(value)}}`).join('');
  return `<${tag}${attrs}>${children}</${tag}>`;
}
const icons = Object.entries(names).map(([name, icon]) => {
  let block = source.split(/\/\/ src\/components\//).find(part => part.includes(`var ${icon} =`));
  if (!block) throw new Error(`Missing ${icon}`);
  block = block.slice(block.indexOf(`var ${icon} =`)).replace(/\/\*.*?\*\//gs, '')
    .replace(/\bjsxs?\d*\(/g, 'jsx(')
    .replace(/\b(Svg|Path|Rect|Circle|G|Defs|LinearGradient|Stop|ClipPath)\d*\b/g, (_, type) => JSON.stringify(type === 'Svg' ? 'svg' : type[0].toLowerCase() + type.slice(1)));
  const tree = vm.runInNewContext(`${block}\n${icon}({color:'currentColor'});`, { jsx });
  return `    ${name}: <>${[tree.props.children].flat().map(markup).join('')}</>,`;
});
await fs.writeFile(new URL('../src/components/Icon.tsx', import.meta.url), `// Geometry copied without alteration from @yoroll/rn-icon 0.0.18 (ISC), used by Yoroll App.\n// Generated by scripts/extract-app-icons.mjs; only the native SVG wrapper is adapted.\nexport function Icon({ name, size = 22 }: { name: ${Object.keys(names).map(n => `'${n}'`).join(' | ')}; size?: number }) {\n  const icons = {\n${icons.join('\n')}\n  };\n  return <svg width={size} height={size} viewBox="0 0 24 24" fill="none" aria-hidden="true">{icons[name]}</svg>;\n}\n`);
console.log(`Extracted ${icons.length} original App icons.`);
